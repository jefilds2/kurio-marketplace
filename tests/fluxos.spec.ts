test('Socket.IO atualiza cotação antes de confirmar e ignora versões antigas', async ({ page }) => {
  await checkout(page)
  await page.locator('#pagamentos-confirmar').click()
  const resposta = await page.evaluate(async () => {
    const r = await fetch('/api/demo/nft', { method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ nftId: 'nft-01', preco: '1.49' }) })
    return r.status
  })
  expect(resposta).toBe(200)
  await expect(page.getByText('A cotação mudou. Feche e revise os valores atualizados.')).toBeVisible()
  await expect(confirmar(page)).toBeDisabled()
  await page.getByRole('dialog').getByRole('button', { name: 'Fechar' }).click()
  await expect(page.getByText('1.506 ETH')).toBeVisible()
  await page.getByRole('button', { name: 'Cenários', exact: true }).click()
  await page.getByLabel('Repetir evento e enviar versão anterior').check()
  await page.getByRole('button', { name: 'Disparar atualização de NFT' }).click()
  await expect(page.getByText('Cenário disparado.')).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: 'Fechar' }).click()
  await expect(page.getByText('1.506 ETH')).toBeVisible()
})
