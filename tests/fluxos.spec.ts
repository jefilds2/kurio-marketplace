import { expect, test, type Page } from '@playwright/test'

const senha = 'Kurio123!'
const ape = 'Emerald Ape #042'
async function detalhe(page: Page) {
  await page.goto('/nfts/nft-01')
  await expect(page.getByRole('heading', { name: ape })).toBeVisible()
}
async function login(page: Page, email = 'ana@kurio.test') {
  await expect(page.getByRole('heading', { name: 'Entrar', exact: true })).toBeVisible()
  await page.locator('#login-painel-cadastro:visible #login-email-cadastro, #login-painel-entrar:visible #login-email').fill(email)
  await page.locator('#login-painel-cadastro:visible #login-senha-cadastro, #login-painel-entrar:visible #login-senha').fill(senha)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
}
async function cenario(page: Page, nome: string) {
  await page.getByRole('button', { name: 'Cenários', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Cenário ativo').selectOption(nome)
  await expect(dialog.getByLabel('Cenário ativo')).toHaveValue(nome)
  await expect(dialog.getByLabel('Cenário ativo')).toBeEnabled()
  await dialog.getByRole('button', { name: 'Fechar', exact: true }).click()
}
async function checkout(page: Page) {
  await detalhe(page)
  await page.getByRole('button', { name: 'Comprar NFT' }).click()
  await login(page)
  await expect(page.locator('#pagina-pagamentos')).toBeVisible()
  await expect(page.locator('#pagamentos-confirmar')).toBeEnabled()
}
const confirmar = (page: Page) => page.getByRole('dialog', { name: 'Revisar compra' }).getByRole('button', { name: 'Confirmar compra' })

test('catálogo preserva busca, filtros, ordenação, paginação e histórico', async ({ page }, info) => {
  await page.goto('/')
  await expect(page.getByRole('status').filter({ hasText: '20 NFTs' })).toBeVisible()
  await page.getByRole('button', { name: 'Próxima página' }).click()
  await expect(page).toHaveURL(/pagina=2/)
  await expect(page.getByText('Página 2 de 3')).toBeVisible()
  const mobile = info.project.name === 'mobile'
  if (mobile) await page.getByRole('button', { name: 'Abrir filtros' }).click()
  const filtros = mobile ? page.getByRole('dialog') : page.locator('.referencia-filtros')
  if (mobile) await filtros.getByLabel('Colecionáveis', { exact: true }).check()
  else await filtros.locator('label').filter({ hasText: 'Colecionáveis' }).click()
  if (mobile) await filtros.getByLabel('Ethereum', { exact: true }).check()
  else await filtros.locator('label').filter({ hasText: 'Ethereum' }).click()
  if (mobile) {
    await filtros.getByLabel('Ordenação').selectOption('menor-preco')
    await filtros.getByRole('button', { name: 'Ver resultados' }).click()
  } else await page.getByLabel('Ordenação').selectOption('menor-preco')
  await expect(page).toHaveURL(/categorias=.*redes=/)
  await expect(page).toHaveURL(/pagina=1/)
  const busca = page.locator(mobile ? '.referencia-busca-mobile input' : '.referencia-busca-desktop input')
  if (mobile) await busca.fill('Emerald')
  else {
    await page.getByRole('button', { name: 'Buscar', exact: true }).click()
    const pesquisa = page.getByRole('dialog')
    await pesquisa.getByRole('textbox', { name: 'Explorar coleções' }).fill('Emerald')
    await pesquisa.getByRole('button', { name: 'Buscar', exact: true }).click()
  }
  await expect(page.getByRole('status').filter({ hasText: '1 NFTs' })).toBeVisible()
  await page.reload()
  await expect(busca).toHaveValue('Emerald')
  await page.goBack()
  await expect(busca).toHaveValue('')
  await page.goForward()
  await expect(busca).toHaveValue('Emerald')
})
