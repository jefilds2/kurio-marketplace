test('timeout após criação recupera a mesma tentativa após refresh', async ({ page }) => {
  await checkout(page)
  await cenario(page, 'pedido-timeout')
  await page.locator('#pagamentos-confirmar').click()
  let envios = 0
  page.on('request', r => { if (r.method() === 'POST' && r.url().endsWith('/api/pedidos')) envios++ })
  await confirmar(page).dblclick({ force: true })
  await expect(page.getByRole('dialog').getByText(/A resposta demorou/)).toBeVisible({ timeout: 7000 })
  expect(envios).toBe(1)
  await page.reload()
  await page.getByRole('button', { name: 'Consultar ou reenviar tentativa' }).click()
  await expect(page.locator('#confirmacao-titulo')).toBeVisible({ timeout: 9000 })
  expect(envios).toBe(2)
})
